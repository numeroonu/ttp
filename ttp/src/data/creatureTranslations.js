/**
 * Returns localized fields for a creature based on the selected language
 */
export function getLocalizedCreature(creature, language = 'fil') {
  if (!creature) return null
  if (language === 'en') {
    return creature
  }

  const fil = CREATURE_FILIPINO[creature.id]
  if (!fil) {
    return creature
  }

  return {
    ...creature,
    classification: fil.classification || creature.classification,
    dangerLevel: fil.dangerLevel || creature.dangerLevel,
    habitat: fil.habitat || creature.habitat,
    dietOrPrey: fil.dietOrPrey || creature.dietOrPrey,
    teaser: fil.teaser || creature.teaser,
    description: fil.description || creature.description,
    behavior: fil.behavior || creature.behavior,
    signs: fil.signs || creature.signs,
    weakness: fil.weakness || creature.weakness,
    aral: fil.aral || creature.aral,
  }
}
